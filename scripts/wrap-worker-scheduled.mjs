#!/usr/bin/env node
/**
 * Gives the built Worker a `scheduled` handler.
 *
 * `@sveltejs/adapter-cloudflare` generates a worker that exports `fetch` and
 * only `fetch`, and it writes it to whatever `main` in `wrangler.toml` points
 * at — so `main` cannot be a hand-written entry that adds anything to it. Plan
 * §4 needs a Cron Trigger to warm the calendar cache, and a Cron Trigger
 * invokes `scheduled`.
 *
 * So, after `vite build`:
 *
 *   1. the generated `_worker.js` is moved aside to `_sveltekit.js`;
 *   2. a small `_worker.js` is written in its place that re-exports the
 *      adapter's `fetch` untouched and adds `scheduled` from
 *      `src/lib/server/calendar/scheduled.ts`.
 *
 * Wrangler bundles `main` with esbuild on both `dev` and `deploy`, which is
 * what pulls the TypeScript in. The handler itself deliberately lives in
 * `src/` where `svelte-check`, ESLint and Vitest all see it; the generated
 * file below is glue and nothing else.
 *
 * `assert-no-private-prerender.mjs --output` runs *after* this in `pnpm build`,
 * so both files are still scanned. Nothing here changes what is served over
 * HTTP: `fetch` is the adapter's own function, called with the adapter's own
 * arguments.
 *
 * Usage: node scripts/wrap-worker-scheduled.mjs [dir]
 */
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_DIR = join(REPO_ROOT, process.argv[2] ?? join('.svelte-kit', 'cloudflare'));

const WORKER = join(OUTPUT_DIR, '_worker.js');
const SVELTEKIT_WORKER = join(OUTPUT_DIR, '_sveltekit.js');
const HANDLER = join(REPO_ROOT, 'src', 'lib', 'server', 'calendar', 'scheduled.ts');

const GENERATED_MARKER = 'GENERATED by scripts/wrap-worker-scheduled.mjs';

function fail(message) {
	console.error(`\nwrap-worker-scheduled: FAILED\n\n  ✗ ${message}\n`);
	process.exit(1);
}

if (!existsSync(WORKER)) {
	fail(`${relative(REPO_ROOT, WORKER)} does not exist. Run this after \`vite build\`.`);
}

if (!existsSync(HANDLER)) {
	fail(`${relative(REPO_ROOT, HANDLER)} does not exist; there is no scheduled handler to wire.`);
}

// Re-running against an already-wrapped output would make `_sveltekit.js` a
// copy of the wrapper and lose the real worker. `vite build` rewrites
// `_worker.js` from scratch every time, so this only fires on a manual re-run.
if (readFileSync(WORKER, 'utf8').includes(GENERATED_MARKER)) {
	console.error('wrap-worker-scheduled: already wrapped, nothing to do.');
	process.exit(0);
}

renameSync(WORKER, SVELTEKIT_WORKER);

const handlerSpecifier = relative(OUTPUT_DIR, HANDLER).split(/[\\/]/).join('/');

writeFileSync(
	WORKER,
	`// ${GENERATED_MARKER} — do not edit, and do not commit.
// \`fetch\` is the adapter's own handler, passed through unchanged.
// \`scheduled\` is plan §4's calendar cache warmer.
import sveltekit from './_sveltekit.js';
import { scheduled } from '${handlerSpecifier}';

export default {
\tfetch: (request, env, ctx) => sveltekit.fetch(request, env, ctx),
\tscheduled
};
`,
	'utf8'
);

console.error(
	`wrap-worker-scheduled: ok (${relative(REPO_ROOT, WORKER)} now exports fetch + scheduled)`
);
